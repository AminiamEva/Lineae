const assert = require('node:assert/strict');
const { readFile, mkdir } = require('node:fs/promises');
const { resolve } = require('node:path');
const { pathToFileURL } = require('node:url');
const { parse } = require('yaml');
const { chromium } = require('playwright');

(async () => {
  const html = await readFile('docs/shortcut-planner.html', 'utf8');
  const catalog = JSON.parse(/<script id="catalog" type="application\/json">([\s\S]*?)<\/script>/.exec(html)[1]);
  const { chordTimeoutMs, ...defaults } = parse(await readFile('apps/web/config.yaml', 'utf8')).keybindings;
  assert.deepEqual(catalog.defaults, defaults, 'The feature inventory includes every current configurable command and its exact defaults');
  const expectedIds = Object.entries(defaults).flatMap(([scope, commands]) =>
    Object.keys(commands).map(command => scope + '.' + command));
  assert.deepEqual(Object.keys(catalog.labels).sort(), expectedIds.sort(), 'All configured commands have reviewed descriptions');
  const allIds = [...expectedIds, ...catalog.entries.map(row => row[0]), ...catalog.builtins.map(row => row[0])];
  assert.equal(new Set(allIds).size, allIds.length, 'Feature IDs must be unique');
  const { compileKeybindings } = await import('../apps/web/src/editor/keybindings.mjs');
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext({ acceptDownloads: true, offline: true });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const network = [];
    page.on('request', request => { if (/^https?:/.test(request.url())) network.push(request.url()); });
    await page.goto(pathToFileURL(resolve('docs/shortcut-planner.html')).href);
    await page.locator('#platform').selectOption('windows');
    const row = id => page.locator(`tr[data-id="${id}"]`);
    const choose = async (id, decision, keys) => {
      await row(id).locator('select').selectOption(decision);
      if (keys !== undefined) await row(id).locator('textarea').first().fill(keys);
    };
    const exported = () => page.evaluate(() => exportProfile());
    const command = async id => (await exported()).commands.find(entry => entry.id === id);
    const diagnostics = async id => (await command(id)).diagnostics;
    assert.equal(await page.locator('tr[data-id]').count(), allIds.length);
    assert.equal((await command('math.frac')).decision, 'pending');
    assert.ok(!Object.hasOwn(await command('math.frac'), 'requestedBindings'));
    await choose('editor.toggleBold', 'custom', 'ctrl+k ctrl+m');
    compileKeybindings({ chordTimeoutMs, editor: { toggleBold: (await command('editor.toggleBold')).requestedBindings } });
    assert.deepEqual((await command('editor.toggleBold')).requestedBindings, ['ctrl+k ctrl+m']);
    await choose('editor.toggleItalic', 'custom', 'ctrl+k');
    assert.ok((await diagnostics('editor.toggleBold')).some(issue => issue.severity === 'error'), 'Single-stroke/chord prefix collision is detected');
    await choose('editor.toggleItalic', 'none');
    assert.equal((await command('editor.toggleItalic')).requestedBindings, null);
    assert.equal(await row('editor.toggleItalic').locator('textarea').first().isDisabled(), true);
    assert.ok(!(await diagnostics('editor.toggleBold')).some(issue => issue.severity === 'error'));
    await choose('math.frac', 'custom', 'ctrl+k ctrl+m');
    assert.ok(!(await diagnostics('editor.toggleBold')).some(issue => issue.severity === 'error'), 'Disjoint prose/math contexts can reuse keys');
    await choose('source.indent', 'none');
    assert.ok((await diagnostics('source.indent')).some(issue => issue.severity === 'warning'));
    await choose('source.indent', 'custom', 'shift+tab');
    assert.deepEqual((await command('source.indent')).requestedBindings, ['shift+tab'], 'Builtin remapping proposals can use plain keys');
    await choose('editor.toggleCode', 'custom', '');
    assert.equal((await command('editor.toggleCode')).invalid, true, 'Blank custom binding is not silently treated as unbound');
    await choose('editor.toggleCode', 'none');
    await row('editor.section').getByRole('button').click();
    await page.locator('#record-length').selectOption('2');
    await page.locator('#record-clear').focus();
    await page.keyboard.press('Control+k');
    await page.keyboard.press('Control+m');
    assert.equal(await page.locator('#record-value').textContent(), 'ctrl+k ctrl+m');
    await page.locator('#record-use').click();
    assert.deepEqual((await command('editor.section')).requestedBindings, ['ctrl+k ctrl+m']);
    await page.locator('#platform-notes').fill('Windows preferences');
    await page.locator('#search').fill('分式');
    const download = await Promise.all([page.waitForEvent('download'), page.locator('#export').click()]).then(([file]) => file);
    await mkdir('test-results/shortcut-planner', { recursive: true });
    const windowsFile = resolve('test-results/shortcut-planner/test-windows.json');
    await download.saveAs(windowsFile);
    const windows = JSON.parse(await readFile(windowsFile, 'utf8'));
    assert.equal(windows.platform, 'windows');
    assert.equal(windows.commands.length, allIds.length, 'Export is not truncated by filters');
    await page.locator('#search').fill('');
    await page.locator('#platform').selectOption('macos');
    assert.equal((await command('editor.toggleBold')).decision, 'pending');
    await choose('editor.undo', 'keep');
    await choose('math.undo', 'keep');
    assert.deepEqual((await command('editor.undo')).requestedBindings, ['meta+z']);
    assert.deepEqual((await command('math.undo')).requestedBindings, ['ctrl+z'], 'Literal Control defaults must not silently become Command');
    await choose('editor.toggleBold', 'custom', 'cmd+shift+m');
    assert.deepEqual((await command('editor.toggleBold')).requestedBindings, ['shift+meta+m']);
    await choose('editor.literalBacktick', 'custom', 'ctrl+backslash');
    compileKeybindings({ chordTimeoutMs, editor: { literalBacktick: (await command('editor.literalBacktick')).requestedBindings } }, { isMac: true });
    await page.locator('#platform-notes').fill('<img src=x onerror=alert(1)> Mac preferences');
    const macos = await exported();
    await page.reload();
    await page.locator('#platform').selectOption('macos');
    assert.deepEqual(await exported().then(data => data.commands), macos.commands, 'Browser draft survives reload');
    await page.locator('#platform').selectOption('windows');
    assert.equal((await command('editor.toggleBold')).input, 'ctrl+k ctrl+m', 'Windows decisions remain independent');
    assert.equal(await page.locator('#platform-notes').inputValue(), windows.notes);
    await choose('editor.toggleBold', 'none');
    page.once('dialog', dialog => dialog.accept());
    await page.locator('#import-file').setInputFiles(windowsFile);
    await page.waitForFunction(() => document.getElementById('message').textContent.startsWith('已导入'));
    assert.equal((await command('editor.toggleBold')).input, 'ctrl+k ctrl+m');
    await page.locator('#import-file').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{"version":1}') });
    await page.waitForFunction(() => document.getElementById('message').textContent.startsWith('导入失败'));
    assert.equal((await command('editor.toggleBold')).decision, 'custom', 'Invalid import leaves the draft unchanged');
    assert.deepEqual(errors, []);
    assert.deepEqual(network, [], 'The worksheet works fully offline without external requests');
    const isolated = await browser.newContext({ offline: true });
    await isolated.addInitScript(() => Object.defineProperty(window, 'localStorage', { get() { throw new Error('Storage disabled'); } }));
    const noStorage = await isolated.newPage();
    await noStorage.goto(pathToFileURL(resolve('docs/shortcut-planner.html')).href);
    assert.equal(await noStorage.locator('tr[data-id]').count(), allIds.length, 'Unavailable localStorage does not prevent editing/export');
    assert.equal(await noStorage.locator('#export').isEnabled(), true);
    console.log(`Shortcut planner passed: ${expectedIds.length} configured commands, ${allIds.length} reviewed operations; offline, independent profiles, recording, conflicts, import/export and persistence.`);
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });

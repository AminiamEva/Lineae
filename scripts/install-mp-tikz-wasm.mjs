// Vendor the prebuilt mp-tikz-wasm runtime used by the general TikZ studio.
// Run: node scripts/install-mp-tikz-wasm.mjs
import { mkdtemp, mkdir, copyFile, cp, rm, stat, writeFile, readdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';

const version = '0.5.1';
const root = resolve('apps/web/vendor/mp-tikz-wasm');
const bundles = [
  'core', 'cm-tfm', 'cm-type1', 'lm-fonts', 'ps-fonts', 'tex-plain',
  'latex-core', 'latex-extra', 'tikz-snapshot', 'luatex',
  'opentype', 'otf-fonts', 'ghostscript', 'classico', 'latex-doc',
];
const destinationExists = await stat(join(root, 'index.js')).then(() => true, () => false);
if (destinationExists) {
  console.log(`mp-tikz-wasm already installed at ${root}`);
  process.exit(0);
}
async function download(url, dest) {
  let lastError;
  for (let attempt = 1; attempt <= 6; attempt++) {
    try {
      const response = await fetch(url);
      if (!response.ok) throw new Error(`Download failed: ${response.status}`);
      await writeFile(dest, Buffer.from(await response.arrayBuffer()));
      return;
    } catch (error) {
      lastError = error;
      await new Promise(resolve => setTimeout(resolve, attempt * 1000));
    }
  }
  throw lastError;
}

const archive = join(await mkdtemp(join(tmpdir(), 'lineae-tikz-')), `mp-tikz-wasm-${version}.tar.gz`);
const url = `https://github.com/jmckalex/mp-tikz-wasm/releases/download/v${version}/mp-tikz-wasm-${version}.tar.gz`;
console.log(`Downloading ${url}`);
await download(url, archive);
const unpack = join(await mkdtemp(join(tmpdir(), 'lineae-tikz-extract-')), 'release');
await mkdir(unpack, { recursive: true });
execFileSync('tar', ['-xzf', archive, '-C', unpack, '--strip-components=1']);
const dist = join(unpack, 'dist');
await mkdir(join(root, 'bundles'), { recursive: true });
for (const entry of await readdir(dist)) {
  if (entry.endsWith('.js') || entry.endsWith('.mjs') || entry.endsWith('.wasm')) {
    await copyFile(join(dist, entry), join(root, entry));
  }
}
await mkdir(join(root, 'ghostscript'), { recursive: true });
for (const entry of await readdir(join(dist, 'ghostscript'))) {
  if (entry.endsWith('.js') || entry.endsWith('.mjs') || entry.endsWith('.wasm')) {
    await copyFile(join(dist, 'ghostscript', entry), join(root, 'ghostscript', entry));
  }
}
for (const dir of ['render', 'tex', 'vfs']) {
  await mkdir(join(root, dir), { recursive: true });
  for (const entry of await readdir(join(dist, dir))) {
    if (entry.endsWith('.js')) await copyFile(join(dist, dir, entry), join(root, dir, entry));
  }
}
await copyFile(join(dist, 'bundles', 'hot.json'), join(root, 'bundles', 'hot.json'));
for (const bundle of bundles) await cp(join(dist, 'bundles', bundle), join(root, 'bundles', bundle), { recursive: true });
await copyFile(join(unpack, 'LICENSE'), join(root, 'LICENSE'));
await copyFile(join(unpack, 'NOTICE.md'), join(root, 'NOTICE.md'));
await writeFile(join(root, 'README-LINEAE.md'), `# mp-tikz-wasm vendor copy\n\nSource: https://github.com/jmckalex/mp-tikz-wasm\nVersion: ${version}\nLicense: LGPL-3.0-or-later; bundled TeX Live assets retain their upstream licenses.\nSee LICENSE and NOTICE.md.\n\nGenerated by scripts/install-mp-tikz-wasm.mjs.\n`, 'utf8');
const gsArchive = join(await mkdtemp(join(tmpdir(), 'lineae-tikz-gs-')), `mp-tikz-wasm-ghostscript-${version}.tar.gz`);
const gsUrl = `https://github.com/jmckalex/mp-tikz-wasm/releases/download/v${version}/mp-tikz-wasm-ghostscript-${version}.tar.gz`;
console.log(`Downloading ${gsUrl}`);
await download(gsUrl, gsArchive);
const gsUnpack = join(await mkdtemp(join(tmpdir(), 'lineae-tikz-gs-extract-')), 'gs');
await mkdir(gsUnpack, { recursive: true });
execFileSync('tar', ['-xzf', gsArchive, '-C', gsUnpack, '--strip-components=1']);
await mkdir(join(root, 'ghostscript'), { recursive: true });
for (const entry of await readdir(join(gsUnpack, 'dist', 'ghostscript'))) {
  await copyFile(join(gsUnpack, 'dist', 'ghostscript', entry), join(root, 'ghostscript', entry));
}
await rm(gsUnpack, { recursive: true, force: true });

await rm(unpack, { recursive: true, force: true });
console.log(`Installed mp-tikz-wasm ${version} in ${root}`);
